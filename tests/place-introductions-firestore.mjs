import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { initializeApp, deleteApp } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';
assert.equal(process.env.FIRESTORE_EMULATOR_HOST, '127.0.0.1:8085', 'Local demo emulator only');
const app = initializeApp({ projectId: 'demo-camellia' }, 'place-introductions'), db = getFirestore(app);
const server = await createServer({ configFile: false, root: process.cwd(), resolve: { alias: { '@': process.cwd() } }, server: { middlewareMode: true, hmr: false } });
const root = 'camellia_admin/release_phase1';
let slugs = [];
try {
  const { importIntroductions, ensureIntroductionBatch } = await server.ssrLoadModule('/lib/place/introduction-drafts.ts');
  const { PlaceService } = await server.ssrLoadModule('/lib/place/service.ts');
  const { PLACE_INTRODUCTIONS_FUKUOKA: places } = await server.ssrLoadModule('/data/place-introductions-fukuoka.ts');
  slugs = places.map((p) => p.slug);
  const ready = places.find((p) => p.ready), waiting = places.find((p) => !p.ready);
  await db.doc(`${root}/places/${ready.slug}`).set({ slug: ready.slug, name: 'EXISTING', status: 'suspended' });
  const dry = await importIntroductions(db, places, false);
  assert.equal(dry.published.length + dry.drafted.length, 25);
  assert.equal((await db.doc(`${root}/places/${waiting.slug}`).get()).exists, false, 'dry run writes nothing');
  const first = await ensureIntroductionBatch(db, 'test-batch', places, '2026-11-25T00:00:00.000Z');
  assert.deepEqual(first.skipped, [ready.slug], 'an existing (even suspended) place is never overwritten');
  assert.equal((await db.doc(`${root}/places/${ready.slug}`).get()).data().name, 'EXISTING');
  assert.equal(first.published.length, 13);
  assert.equal((await db.doc(`${root}/places/${waiting.slug}`).get()).data().status, 'draft', 'unchecked places stay drafts');
  const service = new PlaceService(db);
  const listed = [];
  let cursor;
  do { const page = await service.list(cursor); listed.push(...page.places); cursor = page.nextCursor; } while (cursor);
  const shown = listed.filter((p) => slugs.includes(p.slug));
  assert.equal(shown.length, 13, 'published introductions appear in the public Place list');
  assert.ok(shown.every((p) => p.listingType === 'introduction' && p.informationCheckedAt && p.officialUrl && p.address));
  const detail = await service.detail(first.published[0]);
  assert.equal(detail.status, 'published');
  await db.doc(`${root}/places/${first.published[0]}`).delete();
  assert.equal(await ensureIntroductionBatch(db, 'test-batch', places), undefined, 'the batch runs only once');
  assert.equal((await db.doc(`${root}/places/${first.published[0]}`).get()).exists, false, 'a place the operator removed is not brought back');
  console.log('place introductions firestore: ok');
} finally {
  for (const slug of slugs) await db.doc(`${root}/places/${slug}`).delete();
  await db.doc(`${root}/config/place_introduction_batches`).delete();
  for (const doc of (await db.collection(`${root}/place_audit`).where('operatorUid', '==', 'script:place-introductions').get()).docs) await doc.ref.delete();
  await server.close();
  await deleteApp(app);
}
